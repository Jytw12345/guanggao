  function trussUsage(w, h) {
    const ww = Math.max(0, Number(w) || 0), hh = Math.max(0, Number(h) || 0);
    const frame = Math.round((2 * ww + 2 * hh) * 10) / 10;
    const one = Math.sqrt(hh * hh + Math.pow(hh * TRUSS_BRACE_K, 2));
    const brace = Math.round(2 * one * 10) / 10;
    const total = Math.round((frame + brace) * 10) / 10;
    return { frame, brace, total, sections: Math.max(1, Math.ceil(total / TRUSS_SECTION - 1e-9)), sectionLen: TRUSS_SECTION };
  }

