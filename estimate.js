  // ============ 门头识别与配方展开 ============
  function matchDoorRecipe(t) {
    const s = t.toLowerCase();
    // 顺序即优先级（2026-11-22 扩到 10 种）：不锈钢必须先于镀锌/彩钢（「不锈钢板」含「钢板」），
    // 亚克力先于 PVC，真石漆先于石材（「真石漆」不被误当石材干挂）。
    for (const key of ['ss', 'alc', 'acr', 'lvf', 'coat', 'stone', 'sheet', 'pvc', 'lightbox', 'spray']) {
      const r = DOOR_RECIPES[key];
      if (r && r.match && r.match.some(k => s.indexOf(k.toLowerCase()) >= 0)) return Object.assign({ key }, r);
    }
    return Object.assign({ key: 'generic' }, DOOR_RECIPES.generic);
  }
  function expandDoorRecipe(recipe, w, h, qty, depth, gap, thick, shape, lampGap, lvfGap) {
    const qtyN = qty > 0 ? qty : 1;
    const area = w * h * qtyN;
    const perim = 2 * (w + h) * qtyN;
    // 深度 0 = 贴墙平面（不算侧包），是用户可设的有效值；只有 undefined/null 才回默认 0.2
    const dep = (depth != null && Number.isFinite(Number(depth))) ? Math.max(0, Number(depth)) : DOOR_DEPTH;
    const wrapArea = perim * dep;
    const gp = (gap != null && Number.isFinite(Number(gap))) ? Math.max(0.2, Number(gap)) : DOOR_GAP;
    const vN = Math.ceil(w / gp) + 1, hN = Math.ceil(h / gp) + 1;
    const vLen = vN * h, hLen = hN * w;
    // 灯箱内部灯条（2026-11-22）：横向排布、纵向按行距，行业 15–25cm；
    // 灯条总长 = 行数 × 单行长(=门头宽) × 套数，12㎡ 6×2 门头 @0.2m = 10 行 × 6m = 60 米。
    const lp = (lampGap != null && Number(lampGap) >= 0.05) ? Number(lampGap) : (Number(WORK_PARAM_DEFAULT.lampGap) || 0.2);
    const stripRows = Math.max(1, Math.ceil(h / lp - 1e-9));
    const stripLen = stripRows * w * qtyN;
    // 铝方通/格栅（2026-11-22）：竖向排布，根数按中心间距算，每根长＝门头高。
    // 12㎡ 6×2 门头 @0.12m = 50 根 × 2 米 = 100 米（与行业 8–15cm 间距一致）。
    const vg = (lvfGap != null && Number(lvfGap) >= 0.05) ? Number(lvfGap) : (Number(WORK_PARAM_DEFAULT.lvfGap) || 0.12);
    const lvfRows = Math.max(1, Math.ceil(w / vg - 1e-9));
    const lvfLen = lvfRows * h * qtyN;
    // perimDepth：包边窄条料按周长×有效侧包深算（侧包0时按0.1米最小收边），与工艺增项同口径。
    const effDepth = dep > 0 ? dep : EXTRA_MIN_DEPTH;
    const by = { area, perim, perimDepth: perim * effDepth * qtyN, fixed: qtyN, stripLen, lvfLen };
    const tk = (thick > 0 ? thick : 0);
    const layers = tk > 0 ? 2 : 1;
    const shp = shape || 'rect';
    const shapeK = SHAPE_FACTOR[shp] || 1;
    const braceN = tk > 0 ? Math.max(4, Math.round(2 * (w + h) / gp)) * qtyN : 0;
    const braceLen = braceN * tk;
    const gridNodes = vN * hN * layers * qtyN;
    const weldPts = Math.round(gridNodes * shapeK) + braceN * 2;
    const weldHrs = Math.round(weldPts * WELD_H_PER_PT * 10) / 10;
    const frame = { thick: tk, shape: shp, shapeK, layers, gap: gp, vN, hN, braceN, braceLen, gridNodes, weldPts, weldHrs };
    const rnd = (x) => Math.round(x * 100) / 100;
    const work = recipe.work.map(x => ({
      id: x.id, q: rnd(by[x.by] * x.k), note: x.note, u: x.u,
      calc: `${x.by === 'area' ? '面积 ' + area.toFixed(2) + '㎡'
        : x.by === 'perim' ? '周长 ' + perim.toFixed(1) + '米'
          : x.by === 'stripLen' ? '灯条 @' + lp + 'm 行距 横' + stripRows + '根×' + w + '米 = ' + stripLen.toFixed(0) + '米'
            : x.by === 'lvfLen' ? '方通 @' + vg + 'm 间距 竖' + lvfRows + '根×' + h + '米 = ' + lvfLen.toFixed(0) + '米'
              : qtyN + '套'} × ${x.k}`
    }));
    const mat = recipe.mat.map(x => {
      const baseArea = x.wrap ? area + wrapArea : area;
      const areaQty = baseArea * x.k;
      let q, calc, netQty = 0, bars = 0, barLeft = 0;
      if (x.by === 'grid') {
        const dir = x.gridDir || 'both';
        const oneLen = dir === 'v' ? vLen : dir === 'h' ? hLen : vLen + hLen;
        q = Math.max(1, Math.round(oneLen * qtyN * x.k)) * layers;
        // 只做提示：按 6 米定尺算需几根、切完余几米；工程款仍按净米数计（不改金额）
        bars = Math.ceil(q / TUBE_LEN);
        barLeft = Math.round((bars * TUBE_LEN - q) * 100) / 100;
        const detail = dir === 'v' ? `竖${vN}根×${h}m=${vLen.toFixed(1)}米`
          : dir === 'h' ? `横${hN}根×${w}m=${hLen.toFixed(1)}米`
            : `竖${vN}根×${h}m + 横${hN}根×${w}m = ${(vLen + hLen).toFixed(1)}米`;
        calc = `@${gp}m间距 ${detail}` + (qtyN > 1 ? ` × ${qtyN}套` : '') + (x.k !== 1 ? ` × ${x.k}` : '') + (layers > 1 ? ` ×2层=${q}米` : '');
      } else if (x.u === '㎡' && x.by === 'area') {
        q = Math.max(1, rnd(areaQty));
        netQty = q; // 整张取整前的净用量，供结果行标「呆料」
        calc = x.wrap
          ? `正面${area.toFixed(2)} + 侧包${wrapArea.toFixed(2)}(${dep}米深) = ${baseArea.toFixed(2)}㎡ × ${x.k}`
          : `面积 ${area.toFixed(2)}㎡ × ${x.k}`;
      } else {
        q = Math.max(1, Math.round(by[x.by] * x.k));
        calc = x.by === 'stripLen'
          ? `灯条 @${lp}m 行距 横${stripRows}根×${w}米 = ${stripLen.toFixed(0)}米 × ${x.k}`
          : x.by === 'lvfLen'
            ? `方通 @${vg}m 间距 竖${lvfRows}根×${h}米 = ${lvfLen.toFixed(0)}米 × ${x.k}`
            : x.by === 'perimDepth'
              ? `周长 ${perim.toFixed(1)}米 × ${effDepth}米深${dep > 0 ? '' : '(侧包0→按0.1米收边)'} = ${(perim * effDepth).toFixed(2)}㎡ × ${x.k}`
              : `${x.by === 'perim' ? '周长 ' + perim.toFixed(1) + '米' : qtyN + '套'} × ${x.k}`;
      }
      let sheets = x.sheet ? Math.ceil(areaQty / SHEET_AREA) : 0;
      let sheetHow = '';
      if (x.sheet) {
        // 2026-11-23：门头高超过板长 2.44m 必须拼接，纯面积法会少算张数。
        // 按宽高排板兜底，只在排板张数更多时生效（常规尺寸一分不变）。
        const lay = sheetLayoutCount(w, h);
        const layN = lay.n * qtyN;
        if (layN > sheets) { sheets = layN; sheetHow = lay.how; }
      }
      if (sheets) {
        // 板材按整张买（2026-11-22）：不足一张算一张，工程量与金额都按整张面积×单价，
        // 不能按「用得上的面积」收钱——否则 5.6 张的活只收 5.6 张不到的料钱。
        q = Math.round(sheets * SHEET_AREA * 100) / 100;
        calc += ` → 按整张 ${sheets}张 × ${SHEET_AREA}㎡ = ${q}㎡（不足一张按一张）`;
        if (sheetHow) calc += `；高${h}米超板长${SHEET_H}米需拼接·按${sheetHow}排${sheets}张`;
      }
      return { n: x.n, u: x.u, q, p: x.p, sheets, sheetHow, wrap: !!x.wrap, calc, netQty, bars, barLeft };
    });
    if (tk > 0 && braceLen > 0) {
      mat.push({ n: '方管(双层连接撑)', u: '米', q: Math.round(braceLen), p: 24, sheets: 0, wrap: false,
        calc: `厚度${tk}m × 连接撑${braceN}根 = ${braceLen.toFixed(1)}米` });
    }
    return { work, mat, area, perim, wrapArea, depth: dep, gap: gp, vN, hN, frame };
  }
  /* 工艺增项算量：sel 为 {key:true} 勾选表，defs 为工艺库（内置 + 自定义）。
     返回 { work:[], mat:[] }，结构与 expandDoorRecipe 的输出一致，供 tryDoorRecipe 合并。*/
  function expandDoorExtras(defs, sel, d) {
    const dep = d.depth != null ? Number(d.depth) : DOOR_DEPTH;
    const effDepth = dep > 0 ? dep : EXTRA_MIN_DEPTH;
    const qtyN = d.qtyN > 0 ? d.qtyN : 1;
    // 脚手架有效高度：文字写了「离地X米」时按 离地净高+门头高 算层数；台阶不抵减。
    const scH = Number(d.scaffoldH) > 0 ? Number(d.scaffoldH) : d.h;
    const scExtra = scH > d.h ? `（门头${d.h}米+离地${(scH - d.h).toFixed(2).replace(/\.00$/, '')}米）` : '';
    // 檐口/滴水线的有效长度：上沿（=宽）+ 两个上转角返边，不按整圈周长
    const edgeLen = (d.w + 2 * effDepth) * qtyN;
    const baseOf = (by) => {
      if (by === 'perim') return d.perim;
      if (by === 'perimDepth') return d.perim * effDepth;
      if (by === 'edgeLen') return edgeLen;
      if (by === 'canopy') return d.w * 0.8 * qtyN;
      if (by === 'scaffold') return scaffoldSets(d.w, scH);
      if (by === 'fixed') return qtyN;
      return d.area;
    };
    const methodTxt = (by, k) => by === 'perimDepth'
      ? `周长 ${d.perim.toFixed(1)}米 × ${effDepth}米深` + (dep > 0 ? '' : '（侧包0→按0.1米收边）')
      : by === 'perim' ? `周长 ${d.perim.toFixed(1)}米`
        : by === 'edgeLen' ? `宽 ${d.w}米 + 两侧返边 ${(2 * effDepth).toFixed(1)}米 = ${edgeLen.toFixed(1)}米`
          : by === 'canopy' ? `宽 ${d.w}米 × 0.8米出挑`
            : by === 'scaffold' ? `宽 ${d.w}米÷1.8=${Math.ceil(d.w / 1.8)}片 × 有效高 ${scH}米${scExtra}叠${Math.ceil(Math.max(0, scH - SCAFFOLD_REACH) / SCAFFOLD_UNIT_H)}层 = ${scaffoldSets(d.w, scH)}组`
              : by === 'fixed' ? `${qtyN} 套` : `面积 ${d.area.toFixed(2)}㎡`;
    const rnd = (x) => Math.round(x * 100) / 100;
    // 折合护栏：把 bench.per 换成「这一项的对照量」，配置页/勾选区按 金额÷对照量 与行业上限比
    const benchOf = (ex) => {
      const b = ex.bench;
      if (!b) return null;
      const per = b.per === 'edge' ? edgeLen
        : b.per === 'm' ? d.perim
          : b.per === 'canopy' ? d.w * 0.8 * qtyN
            : b.per === 'group' ? scaffoldSets(d.w, scH)
              : d.area;
      return { per: b.per, qty: per, hi: Number(b.hi) || 0 };
    };
    const work = [], mat = [];
    (defs || []).forEach(ex => {
      if (!ex || !ex.key || !sel || sel[ex.key] !== true) return;
      const bench = benchOf(ex);
      const wq = ex.work && ex.work.id ? rnd(Math.max(0, baseOf(ex.work.by) * (Number(ex.work.k) || 0))) : 0;
      if (wq > 0) {
        const it = getWorkItem(ex.work.id);
        if (it) {
          work.push({ id: ex.work.id, q: wq, note: ex.work.note || ex.n, u: it.u, extraKey: ex.key, bench,
            calc: `工艺·${ex.n}：${methodTxt(ex.work.by)} × ${ex.work.k}` });
        }
      }
      const m = ex.mat;
      // 材料系数填 0 = 这一项不算材料（脚手架、自有工具这类按需关掉）
      if (m && m.n && Number(m.k) > 0) {
        // 不再把不足 1 个单位抬成 1（小门头 0.6㎡ 包边料按 1㎡ 收＝虚增），按实算量，量 0 才不列
        let q = rnd(baseOf(m.by) * (Number(m.k) || 0));
        if (!(q > 0)) return;
        let calc = `工艺·${ex.n}`;
        const byTxt = methodTxt(m.by);
        let sheets = 0, netQty = 0, sheetHow = '';
        if (m.sheet) {
          netQty = q; // 整张取整前净用量
          sheets = Math.ceil(q / SHEET_AREA);
          // 背板这类整面 area 板材按门头宽高排板；包边 perimDepth 是窄条，不套排版
          if (m.by === 'area') {
            const lay = sheetLayoutCount(d.w, d.h);
            const layN = lay.n * qtyN;
            if (layN > sheets) { sheets = layN; sheetHow = lay.how; }
          }
          q = rnd(sheets * SHEET_AREA);
          calc += `：${byTxt} × ${m.k} → 按整张 ${sheets}张 = ${q}㎡` + (sheetHow ? `（高${d.h}米需拼接·${sheetHow}）` : '');
        } else {
          calc += `：${byTxt} × ${m.k} = ${q}${m.u || ''}`;
        }
        mat.push({ n: m.n, u: m.u || '项', q, p: Number(m.p) || 0, sheets, sheetHow, wrap: false, calc, extraKey: ex.key, bench, netQty });
      }
    });
    return { work, mat };
  }
  /* 工艺库 = 内置（可隐藏/可覆盖）+ 自定义。
     同 key 时用自定义项「按字段覆盖」内置项：只改了材料单价的内置工艺，人工定额不会丢。*/
  function doorExtraDefs(custom, hidden) {
    const hs = new Set(Array.isArray(hidden) ? hidden : []);
    const arr = Array.isArray(custom) ? custom.filter(x => x && x.key && !hs.has(x.key)) : [];
    const ov = new Map(arr.map(x => [String(x.key), x]));
    const out = DOOR_EXTRAS.filter(x => !hs.has(x.key)).map(x => {
      const o = ov.get(x.key);
      if (!o) return x;
      ov.delete(x.key);
      const merged = Object.assign({}, x, o);
      if (x.work || o.work) merged.work = Object.assign({}, x.work || {}, o.work || {});
      if (x.mat || o.mat) merged.mat = Object.assign({}, x.mat || {}, o.mat || {});
      return merged;
    });
    // 剩下的 key 才是真正的自定义工艺
    ov.forEach(v => out.push(v));
    return out;
  }
  /* 是否按「门头配方」拆解（2026-11-22）：
     - 门头/店招/门脸：老口径不变，只要写了尺寸就展开配方；
     - 招牌：新口径——写了尺寸才算门头（「招牌 6×2米」也能展开，「招牌制作」不带尺寸仍走定额）；
     - 纯拆除（门头拆除/招牌拆旧…）一律不展开配方，否则会把「拆」算成「新建一套」。
     GG 层也用这个函数判断 isDoorText，避免前后端口径不一致。*/
  function isRemoveOnly(t) {
    const s = String(t || '');
    return /拆除|拆旧|拆掉|撤除|清拆|拆移/.test(s) && !/新装|再装|重装|安装|制作|更换|换新|重做|翻新|改造|新建/.test(s);
  }
  /* 免挖坑判定（2026-11-25）：停车场立柱常见两种做法——挖坑栽柱 vs 水泥地面打孔装螺丝。
     用户写「水泥地面打孔装膨胀螺丝/化学锚栓」时明确不打坑，此时要抑制 i_pitbase/i_pitmach，
     否则词典里的「栽立柱/立杆」会把水泥地打孔误算成挖坑（多算工、多算坑）。
     判据：出现「打孔固定」类词 + 地面/水泥/混凝土场景，且没有明确的挖坑/开挖词。 */
  function isNoDigOnly(t) {
    const s = String(t || '');
    const fixed = /打孔|钻孔|打眼|植筋|膨胀螺丝|膨胀螺栓|化学锚栓|涨塞|胀栓|打螺丝|上螺丝|拧螺丝|螺丝固定/.test(s);
    if (!fixed) return false;
    const ground = /水泥|混凝土|地面|地坪|水泥地|硬地|打膨胀/.test(s);
    // 只有明确动土才算真要挖；「立杆」这类只描述立起来的模糊词不算，以免误伤打孔场景。
    const dig = /挖坑|开挖|基坑|栽柱|栽立柱|埋柱|预埋|挖机|机械挖/.test(s);
    return ground && !dig;
  }
  function isDoorText(t) {
    const s = String(t || '');
    if (isRemoveOnly(s)) return false;
    if (/门头|店招|门脸/.test(s)) return true;
    if (/招牌/.test(s)) { const z = parseSize(s); return !!(z && z.area); }
    return false;
  }
  /* 门头「厚度」识别（2026-11-25）：文字写了厚 20厘米 / 20cm厚 / 厚度0.3米 时，
     本次拆解的侧包深度与骨架厚度都按它算（前后双层框架 + 连接撑 + 侧包面积）。
     只认带单位的箱体厚度：3mm 铝板、1.2mm 不锈钢这类板厚不改成箱体，
     「发光字厚5厘米」是字壳厚度也不误伤。解析结果只作用于本次拆解，不写回配置。*/
  const DOOR_THICK_CN = { 一:1, 二:2, 两:2, 三:3, 四:4, 五:5, 六:6, 七:7, 八:8, 九:9, 十:10 };
  function doorThickNum(s) {
    if (/^\d+(?:\.\d+)?$/.test(s)) return parseFloat(s);
    if (DOOR_THICK_CN[s] != null) return DOOR_THICK_CN[s];
    const m = String(s).match(/^([二三四五六七八九])?十([一二三四五六七八九])?$/);
    if (m) return (m[1] ? DOOR_THICK_CN[m[1]] : 1) * 10 + (m[2] ? DOOR_THICK_CN[m[2]] : 0);
    return NaN;
  }
  function parseDoorThickness(t) {
    const s = String(t || '');
    if (!/厚/.test(s)) return null;
    const NUM = '([0-9]+(?:\\.[0-9]+)?|[一二两三四五六七八九十]+)';
    const UNIT = '(毫米|mm|厘米|公分|cm|米|m)';
    const pats = [
      new RegExp('厚\\s*度?\\s*' + NUM + '\\s*' + UNIT, 'gi'),       // 厚20厘米 / 厚度 0.3 米
      new RegExp(NUM + '\\s*' + UNIT + '\\s*(?:的)?\\s*厚\\s*度?', 'gi') // 20cm厚 / 30公分厚的门头
    ];
    const hits = [];
    pats.forEach(re => { let m; while ((m = re.exec(s)) != null) hits.push(m); });
    hits.sort((a, b) => a.index - b.index);
    for (const m of hits) {
      const before = s.slice(0, m.index).replace(/\s+$/, '');
      if (/(?:字|字壳|字面)$/.test(before)) continue; // 字壳厚≠箱体厚
      const raw = doorThickNum(m[1]);
      if (!(raw > 0)) continue;
      const unit = m[2];
      let meters;
      if (/毫米|mm/i.test(unit)) {
        if (raw < 80) continue; // <8cm 按板厚/包边料厚忽略
        meters = raw / 1000;
      } else if (/厘米|公分|cm/i.test(unit)) meters = raw / 100;
      else meters = raw;
      meters = Math.round(meters * 1000) / 1000;
      if (meters < 0.05 || meters > 1) continue;
      return { meters, raw, unit, text: m[0].trim() };
    }
    return null;
  }
  /* 门头离地净高（2026-11-25）：「离地3米 / 距地面2.4米 / 门头底离地80公分」。
     脚手架按「离地净高 + 门头高」折算层数；台阶只当通行方式，不抵减高度。
     与板厚同理：只作用于本次拆解，不写回配置。*/
  function parseDoorClearance(t) {
    const s = String(t || '');
    const NUM = '([0-9]+(?:\\.[0-9]+)?|[一二两三四五六七八九十]+)';
    const UNIT = '(毫米|mm|厘米|公分|cm|米|m)';
    const re = new RegExp('(?:离|距(?:离)?)\\s*(?:地(?:面)?)?\\s*(?:高度|高)?\\s*' + NUM + '\\s*' + UNIT, 'i');
    const m = s.match(re);
    if (!m) return null;
    const raw = doorThickNum(m[1]);
    if (!(raw > 0)) return null;
    const unit = m[2];
    let meters;
    if (/毫米|mm/i.test(unit)) meters = raw / 1000;
    else if (/厘米|公分|cm/i.test(unit)) meters = raw / 100;
    else meters = raw;
    meters = Math.round(meters * 1000) / 1000;
    if (meters < 0.05 || meters > 20) return null;
    return { meters, text: m[0].trim() };
  }
  function tryDoorRecipe(t, doorCfg) {
    const cfg = doorCfg || {};
    if (!isDoorText(t)) return null;
    const sz = parseSize(t);
    if (!sz || !sz.area) return null;
    let w = 0, h = 0;
    let m = t.match(/(\d+(?:\.\d+)?)\s*(?:米|m|cm|厘米|公分|mm|毫米)?\s*[×x*＊.]\s*(\d+(?:\.\d+)?)/i);
    if (m) {
      let a = parseFloat(m[1]), b = parseFloat(m[2]);
      const hasCm = /cm|厘米|公分/i.test(m[0]);
      const unitAfter = /^\s*(米|m\b)/i.test(t.slice(m.index + m[0].length)); // 「6×2米」单位在后
      const hasM = /米|m\b/i.test(m[0]) || unitAfter;
      if (hasCm) { a /= 100; b /= 100; }
      if (!hasM && !hasCm) { const meter = String(m[1]).indexOf('.') >= 0 || String(m[2]).indexOf('.') >= 0; if (!meter) { a /= 100; b /= 100; } }
      w = Math.max(a, b); h = Math.min(a, b);
    }
    if (!w || !h) { w = Math.sqrt(sz.area); h = w; }
    // 「发光字高60厘米5个」「5个不锈钢发光字60厘米的」：字数≠门头套数——字高/字数分开检测，先摘字数段防整体×N
    let charQty = null, charH = null, charPat = null;
    const hm = t.match(/(?:发光字|字)\s*[,，]?\s*高?\s*(\d+(?:\.\d+)?)\s*(mm|毫米|cm|厘米|公分|米|m)\s*(?:的)?/i); // 字高：带单位（高字可省）
    if (hm) {
      charH = parseFloat(hm[1]);
      const cu = hm[2] || '';
      if (/mm|毫米/i.test(cu)) charH /= 1000;
      else if (/cm|厘米|公分/i.test(cu)) charH /= 100;
      else if (!/米|m/i.test(cu) && charH > 3) charH /= 100; // 无单位按厘米兜底
    }
    if (charH == null) {
      // 「4个55厘米高的发光字」：字高写在「字」前面（数量/尺寸在前），与上一条互补。
      // 只认紧挨着「发光字/字」的尺寸，避免把「4米的门头」误当字高。
      const hm2 = t.match(/(\d+(?:\.\d+)?)\s*(mm|毫米|cm|厘米|公分|米|m)\s*(?:高)?\s*(?:的)?\s*(?:发光字|字)/i);
      // 「6×2米 发光字…」里的 2米 是门头高度不是字高：紧跟在 ×/x 后面的尺寸要跳过
      const beforeHm2 = hm2 ? t.slice(0, hm2.index) : '';
      if (hm2 && !/[×x*＊]\s*$/.test(beforeHm2)) {
        charH = parseFloat(hm2[1]);
        const cu2 = hm2[2] || '';
        if (/mm|毫米/i.test(cu2)) charH /= 1000;
        else if (/cm|厘米|公分/i.test(cu2)) charH /= 100;
        else if (!/米|m/i.test(cu2) && charH > 3) charH /= 100;
      }
    }
    let cm = t.match(/(\d+(?:\.\d+)?)\s*个\s*([^，,。；;]{0,12}?)(?:发光字|字)/i); // 「4个(55厘米高的)发光字」：中间允许数量/尺寸词
    if (cm && /门头|店招|门脸|招牌|射灯|灯条|灯箱|电源|制作|安装|焊接|加工|施工|拆除|维修/.test(cm[2])) cm = null;
    if (!cm) { // 「发光字5个/发光字高60厘米5个/发光字60厘米的，5个/发光字5个60厘米」式：字高段可选，个后须是句尾/标点/动词防误伤「发光字，5个射灯」
      // 2026-11-22：个后允许再跟一段字高（「发光字5个60厘米」很常见），否则「5个」会被当成 5 套门头（面积翻 5 倍）
      const m5 = t.match(/(?:发光字|字)\s*[,，]?\s*(?:高)?\s*(?:(?:\d+(?:\.\d+)?)\s*(?:mm|毫米|cm|厘米|公分|米|m)?\s*(?:的)?\s*)?[,，]?\s*(\d+(?:\.\d+)?)\s*个\s*(?:\d+(?:\.\d+)?\s*(?:mm|毫米|cm|厘米|公分|米|m)\s*(?:高)?)?/i);
      const tailOk = m5 && /^(制作|安装|加工|焊接|施工|亮化|$|[，,、；;。\s])/i.test(t.slice(m5.index + m5[0].length));
      if (tailOk) cm = m5;
    }
    if (cm) {
      charQty = parseFloat(cm[1]); charPat = cm[0];
      // 字高写在「N个」后面（发光字5个60厘米）时，从同一段里补出来，字面积才算得准
      if (charH == null) {
        const hv = cm[0].match(/(\d+(?:\.\d+)?)\s*(mm|毫米|cm|厘米|公分|米|m)/i);
        if (hv) {
          charH = parseFloat(hv[1]);
          if (/mm|毫米/i.test(hv[2])) charH /= 1000;
          else if (/cm|厘米|公分/i.test(hv[2])) charH /= 100;
          else if (!/米|m/i.test(hv[2]) && charH > 3) charH /= 100;
        }
      }
    }
    let qty = 1;
    const tDoor = charPat ? t.replace(charPat, ' ') : t;
    const qm = tDoor.match(/(\d+(?:\.\d+)?)\s*(?:个|套|块|面|处)/);
    if (qm) {
      const before = tDoor.slice(0, qm.index);
      const after = tDoor.slice(qm.index + qm[0].length);
      // 跳过「55厘米高的」这类尺寸修饰，再判断后面跟的是不是别的物料（射灯/发光字/灯条…）
      const afterKey = after.replace(/^\s*\d+(?:\.\d+)?\s*(?:mm|毫米|cm|厘米|公分|米|m)?\s*(?:高|长的?|宽的?|大的?)?\s*(?:的)?\s*/i, '');
      const isOther = /^(射灯|灯|电源|灯条|字|发光|不锈钢|亚克力|pvc|钛金|螺丝|螺杆|螺栓|膨胀)/i.test(afterKey); // 「5个射灯/不锈钢发光字」等：数量属于其他物料，不是门头套数
      if (!/[×x*＊.]\s*$/.test(before) && !isOther) qty = parseFloat(qm[1]) || 1;
    }
    const recipe = matchDoorRecipe(t);
    const elCfg = cfg.params || WORK_PARAM_DEFAULT;
    // 文字写明厚度时，本次拆解覆盖配置的侧包深度/骨架厚度（配置值不动）；
    // 没写厚度则完全沿用旧口径（v429：不污染高频正常路径）。
    const thickness = parseDoorThickness(t);
    const dep = thickness ? thickness.meters : (cfg.depth != null ? cfg.depth : DOOR_DEPTH);
    const tk = thickness ? thickness.meters : (cfg.thick != null ? cfg.thick : 0);
    // 离地净高只影响脚手架组数（离地+门头高=有效作业高度），不改骨架/面板用料
    const clearance = parseDoorClearance(t);
    const scaffoldH = clearance ? Math.round((clearance.meters + h) * 1000) / 1000 : h;
    const ex = expandDoorRecipe(recipe, w, h, qty,
      dep, cfg.gap != null ? cfg.gap : DOOR_GAP,
      tk, cfg.shape || 'rect',
      cfg.lampGap != null ? cfg.lampGap : elCfg.lampGap,
      cfg.lvfGap != null ? cfg.lvfGap : elCfg.lvfGap);
    // 新配方（铝方通/石材/真石漆/镀锌板）主干不含发光字：只有文字里点了「发光字」才补一行，
    // 避免像铝塑板那样默认按面积 40% 估字、白加一笔钱。
    let addedGlow = false;
    if (recipe.autoGlow && /发光字|LED字|灯字/i.test(t)) {
      const qtyN2 = qty > 0 ? qty : 1;
      const glowArea = (charQty && charH) ? Math.round(charQty * charH * charH * 100) / 100 : Math.round(ex.area * 0.4 / qtyN2 * 100) / 100;
      const charTxt = charQty ? (charQty + '个字' + (charH ? ' · 字高' + charH + '米' : '')) : '按门头面积 40% 估字';
      ex.work.push({ id: 'i_led', q: Math.round(glowArea * qtyN2 * 100) / 100, note: '发光字安装（按字占面积估）', u: '㎡',
        calc: charTxt + ' ≈ ' + glowArea + '㎡/套' });
      ex.mat.push({ n: '发光字', u: '㎡', q: Math.round(glowArea * qtyN2 * 100) / 100, p: 500, sheets: 0, wrap: false,
        calc: charTxt + ' ≈ ' + glowArea + '㎡/套' });
      addedGlow = true;
    }
    // 按字数重算发光字相关行：字面积≈字数×字高²（字宽≈字高估）
    if (charQty) {
      const qtyN2 = qty > 0 ? qty : 1;
      const glowArea = charH ? Math.round(charQty * charH * charH * 100) / 100 : null;
      const charTxt = charQty + '个字' + (qtyN2 > 1 ? '×' + qtyN2 + '套' : '') + (charH ? ' · 字高' + charH + '米' : '');
      ex.work.forEach(x => {
        if (x.id === 'i_led' && glowArea != null) { x.q = glowArea * qtyN2; x.calc = charTxt + ' ≈ ' + glowArea + '㎡/套'; }
      });
      ex.mat.forEach(x => {
        if (x.n && x.n.indexOf('发光字') >= 0 && glowArea != null) { x.q = glowArea * qtyN2; x.calc = charTxt + ' ≈ ' + glowArea + '㎡/套'; }
      });
    }
    // 电源只带 12V 负载；灯带/射灯默认 220V 市电直供（可在「参数与单价」改成 12V）。
    // 发光字模组约 60W/㎡、灯带 12W/米、射灯 9W/个；400W 电源按 80% 负载（320W/个）。
    {
      const el = cfg.params || WORK_PARAM_DEFAULT;
      const ledW = Number(el.ledW) || 60, stripW = Number(el.stripW) || 12, spotW = Number(el.spotW) || 9;
      const psuW = Number(el.psuW) || 400, psuLoad = Number(el.psuLoad) || 80;
      // 灯箱布/拉布灯箱的灯条固定走 12V（配方声明 stripVolt:12），其余按参数设置
      const stripV = recipe.stripVolt === 12 ? 12 : (Number(el.stripVolt) === 12 ? 12 : 220);
      const spotV = Number(el.spotVolt) === 12 ? 12 : 220;
      const usableW = Math.max(50, psuW * psuLoad / 100);
      const glowMat = ex.mat.find(x => x.n && x.n.indexOf('发光字') >= 0);
      const stripMat = ex.mat.find(x => x.n && x.n.indexOf('灯条') >= 0);
      const spotMat = ex.mat.find(x => x.n === 'LED射灯');
      const gw = Number(glowMat && glowMat.q) || 0;
      const sw = Number(stripMat && stripMat.q) || 0;
      const pw = Number(spotMat && spotMat.q) || 0;
      const load12 = gw * ledW + (stripV === 12 ? sw * stripW : 0) + (spotV === 12 ? pw * spotW : 0);
      const load220 = (stripV === 220 ? sw * stripW : 0) + (spotV === 220 ? pw * spotW : 0);
      const psuQ = Math.max(1, Math.ceil(load12 / usableW - 1e-9));
      const psu = ex.mat.find(x => x.n === 'LED电源');
      if (psu) {
        psu.q = psuQ;
        psu.calc = `12V负载≈${Math.round(load12)}W ÷ ${Math.round(usableW)}W/个（${psuW}W×${psuLoad}%）；220V直供≈${Math.round(load220)}W`;
      }
      // 电线：树状并联走线，不算「每字整根」：
      // 干线 = 引下配电 3 米 + 沿门头横向 1 倍宽度（多套×套数）
      // 支线 = 每字短接头 0.6 米 + 每只射灯 0.8 米 + 灯带端接 2 米，含 10% 余量
      if (recipe.glow || addedGlow) {
        const nDoors = qty > 0 ? qty : 1;
        const trunk = 3 + w * nDoors;
        const charLead = (charQty || 0) * nDoors * 0.6;
        const spotLead = pw * 0.8;
        const stripLead = sw > 0 ? 2 : 0;
        const wireM = Math.max(10, Math.ceil((trunk + charLead + spotLead + stripLead) * 1.1));
        ex.mat.push({ n: '电线/线缆（2.5mm²）', u: '米', q: wireM, p: 6, sheets: 0, wrap: false,
          calc: `干线(引下3米+横向${(w * nDoors).toFixed(1)}米) + 每字0.6米×${charQty || 0} + 射灯0.8米×${pw} + 灯带端接2米，含10%余量` });
      }
    }
    // 工艺增项（包边/檐口/雨棚…）：只加已勾选的，放在电源/电线之后，不改变负载计算
    {
      const sel = (cfg.extras && typeof cfg.extras === 'object') ? cfg.extras : null;
      if (sel) {
        const defs = doorExtraDefs(cfg.extraDefs, cfg.extraHidden);
        const exd = expandDoorExtras(defs, sel, { area: ex.area, perim: ex.perim, w, h, qtyN: qty > 0 ? qty : 1, depth: ex.depth, scaffoldH });
        exd.work.forEach(x => ex.work.push(x));
        exd.mat.forEach(x => ex.mat.push(x));
      }
    }
    /* 单价库同名行覆盖配方材料价（2026-11-23）：只认精确同名，不做模糊匹配——
       单价库「铝塑板门头 650/㎡」是整门成品口径，绝不能套到材料行「铝塑板 95/㎡」上。
       想覆盖哪项材料，就在单价库建一行名字一模一样的（如「热镀锌方管(骨架)」「铝塑板」）。 */
    const catP = (cfg.catP && typeof cfg.catP === 'object') ? cfg.catP : null;
    if (catP) ex.mat.forEach(x => {
      const cp = Number(catP[x.n]);
      if (cp > 0 && cp !== Number(x.p)) { x.p = cp; x.calc += ' · 单价库'; }
    });
    const hits = [];
    ex.work.forEach(x => {
      const it = getWorkItem(x.id); if (!it) return;
      hits.push({ type: 'lib', id: x.id, n: it.n, u: it.u, q: x.q, calc: x.calc + ' · ' + x.note, kw: recipe.label, note: x.note, extraKey: x.extraKey, bench: x.bench });
    });
    ex.mat.forEach(x => {
      hits.push({ type: 'mat', n: x.n, u: x.u, q: x.q, p: x.p, sheets: x.sheets, sheetHow: x.sheetHow, wrap: x.wrap, calc: x.calc,
        netQty: x.netQty, bars: x.bars, barLeft: x.barLeft, kw: recipe.label, extraKey: x.extraKey, bench: x.bench });
    });
    const extra = parseSpec(t, { synonyms: cfg.synonyms });
    const covered = new Set(ex.work.map(x => x.id));
    extra.forEach(e => {
      if (e.type === 'lib' && covered.has(e.id)) return;
      // i_ledz 是「单独发光字 N个」的按字口径；门头配方已按字数×字高²出 i_led，不能再补一次
      if (e.type === 'lib' && /^(i_door|i_fascia|i_led|i_ledz|i_wire|i_steel|i_ssword|i_acrword|i_banner)$/.test(e.id)) return;
      hits.push(e);
    });
    // charQty/charH 回传：GG 层据此判断发光字面积是真按字数算、还是按门头面积 40% 暂估
    return { hits, recipe, area: ex.area, perim: ex.perim, wrapArea: ex.wrapArea, depth: ex.depth, gap: ex.gap, w, h, qty, charQty, charH,
      thickness: thickness ? thickness.meters : 0, thicknessText: thickness ? thickness.text : '',
      clearance: clearance ? clearance.meters : 0, scaffoldHeight: scaffoldH, frame: ex.frame };
  }

  // ============ 单项解析（万能录入，三种计价模式） ============
  function resolveItem(w, ctx) {
    const p = ctx.params || WORK_PARAM_DEFAULT;
    const WH = ctx.WH || {};
    const dayHours = (p.dayHours > 0 ? p.dayHours : 8);
    // 自定义项（材料/包干/人天/按量）：都是"按钱或按人天"录入，不含定额工时口径，
    // 一律用普通工单价反推，不因项目高度而把包干价换算成天价工时（2026-11-22 修）。
    const rateNormal = p.rateNormal;
    if (w.kind === 'mat') {
      const q = parseFloat(w.q) || 0, price = parseFloat(w.p) || 0;
      const sheetTxt = w.sheets ? ' · 约' + w.sheets + '张' + (w.sheetHow ? '(' + w.sheetHow + ')' : '') : '';
      // 呆料只提示不收钱：板材标净用/整张多出的面积，方管标定尺根数/切余米数。
      // 金额仍是 q×price（q 已按整张/净米数计），改这几行文字不动一分钱。
      const net = Number(w.netQty) || 0;
      const wasteTxt = (w.sheets && net > 0 && q > net)
        ? ` · 净用${net.toFixed(2)}㎡/呆料${(q - net).toFixed(2)}㎡` : '';
      const bars = Number(w.bars) || 0;
      const barTxt = bars > 0
        ? ` · ${TUBE_LEN}米/根 ${bars}根·余${(Number(w.barLeft) || 0).toFixed(0)}米` : '';
      return { n: w.n || '材料', u: w.u || '项', q, hours: 0, fee: q * price,
        note: `材料 ${q}${w.u || ''} × ${price}元${sheetTxt}${wasteTxt}${barTxt}`, isMat: true, isCustom: true };
    }
    if (w.cid) {
      const name = w.n || '自定义项';
      if (w.mode === 'lump') {
        const fee = parseFloat(w.amt) || 0;
        // 包干价不含工时信息：不再 fee/rate 反推假工时（会把 5000 元包干算成上百工时，
        // 进而误导"建议几人几天"）。工时记 0，仅金额进施工费。
        return { n: name, u: '项', q: 1, hours: 0, fee,
          note: '包干价（不计工时）' + (w.note ? ' · ' + w.note : ''), isCustom: true };
      }
      // 设备租赁（2026-11-25）：量×单价进施工费、工时记 0。机械是设备不是人工，
      // 更不能反推工时——否则台班费被折算成上百工时，拉长建议工期→连带抬高高空设备费(equipDays)。
      if (w.mode === 'equip') {
        const q = parseFloat(w.q) || 0, price = parseFloat(w.p) || 0;
        return { n: name, u: w.u || '台班', q, hours: 0, fee: q * price,
          note: `${q}${w.u || '台班'} × ${price}元（设备租赁·不计工时）` + (w.note ? ' · ' + w.note : ''), isCustom: true, isEquip: true };
      }
      // 自定义施工项按工时（2026-11-22）：定额里没有的活，让人自己填「工时/单位」+ 工种，
      // 与定额项同口径：人工费 = 量 × 单位工时 × 工种单价，工时同时参与总工时/人数建议。
      // 不乘高度/墙面系数（工时是人估的，系数由人自己含进去），避免重复计价。
      if (w.mode === 'hours') {
        const q = parseFloat(w.q) || 0, hpu = parseFloat(w.h) || 0;
        const trk = TRADES[w.tr] ? w.tr : 'pg';
        const rate = tradeRate({ tr: trk }, p);
        const hours = q * hpu;
        return { n: name, u: w.u || '项', q, hours, fee: hours * rate,
          note: `${q}${w.u || '项'} × ${hpu}工时 × ${TRADES[trk].n}${rate}元/时`, isCustom: true };
      }
      if (w.mode === 'days') {
        const people = parseFloat(w.people) || 0, days = parseFloat(w.dayPay) || 0;
        const h = people * days * dayHours;  // 用配置的每人每天工时，不再硬编码 8
        const fee = people * days * (parseFloat(w.rate) || 0);
        return { n: name, u: '人天', q: people * days, hours: h, fee,
          note: (w.people || 0) + '人×' + (w.dayPay || 0) + '天 · ' + (w.rate || 0) + '元/人天', isCustom: true };
      }
      const q = parseFloat(w.q) || 0, price = parseFloat(w.p) || 0;
      const fee = q * price;
      return { n: name, u: w.u || '项', q, hours: rateNormal > 0 ? fee / rateNormal : 0, fee, note: q + (w.u || '项') + ' × ' + price + '元', isCustom: true };
    }
    const it = getWorkItem(w.id); if (!it) return null;
    const hf = { low: p.hfLow, mid: p.hfMid, high: p.hfHigh }[ctx.height || 'low'];
    const wf = { flat: p.wfFlat, tile: p.wfTile, glass: p.wfGlass }[ctx.wall || 'flat'];
    const coef = (it.hf ? hf : 1) * (it.wf ? wf : 1);
    const hours = (parseFloat(w.q) || 0) * getH(it, WH) * coef;
    // 工种分价（2026-11）：装板/装字按安装技工、焊接按焊工、接线调试按电工，
    // 不再一律按普工 36 元/时记（等于把技术工当小工算）。高空作业仍取高空工单价且不低于本工种价。
    const baseRate = tradeRate(it, p);
    const isHighWork = ctx.height && ctx.height !== 'low' && it.hf;
    const rate = isHighWork ? Math.max(baseRate, Number(p.rateHigh) || baseRate) : baseRate;
    const fee = hours * rate;
    const note = `标准 ${getH(it, WH)} 工时/${it.u}` + (WH[w.id] != null ? ' · 已校准' : '') + (coef !== 1 ? ` × 系数 ${coef.toFixed(2)}` : '') + ` · ${TRADES[tradeKeyOf(it)].n} ${rate}元/时`;
    return { n: it.n, u: it.u, q: w.q, hours, fee, note, isCustom: false, it };
  }

  // ============ 施工组织建议（只建议，不改金额） ============
  function calcCrew(H, target, p) {
    if (!H || H <= 0) return null;
    const dh = (p.dayHours > 0 ? p.dayHours : 8);
    const isAuto = (target === 'auto');
    const T = isAuto ? 1.5 : (parseFloat(target) || 1);
    const perDay = H / T;
    const level = H <= 2 ? '零星小活' : H <= 8 ? '轻活' : H <= 19 ? '一般活' : H <= 38 ? '较复杂' : H <= 70 ? '复杂活' : '大工程';
    if (H <= 2) {
      const planDays = Math.round(H / dh * 10) / 10;
      return { people: 1, perDay, otHrs: 0, planDays, dh, target, crewCap: dh, level, solo: true };
    }
    let people = Math.max(1, Math.ceil(perDay / dh - 1e-9));
    if (people > 30) people = 30;
    const crewCap = people * dh;
    const planDays = Math.round(H / crewCap * 10) / 10;
    let otHrs = 0;
    if (!isAuto && H > dh * T) otHrs = Math.round(Math.max(0, (H - dh * T) / T) * 10) / 10;
    return { people, perDay, otHrs, planDays, dh, target, crewCap, level };
  }

  // ============ 核心：测算一张清单（纯函数，无 DOM） ============
  // params: { params:WP, WH, height:'low|mid|high', wall:'flat|tile|glass', quote:number }
  function calculate(WORK, ctx) {
    ctx = ctx || {};
    const p = ctx.params || WORK_PARAM_DEFAULT;
    const dayHours = (p.dayHours > 0 ? p.dayHours : 8);
    let totalHours = 0, labor = 0, matFee = 0;
    const rows = [];
    (WORK || []).forEach((w) => {
      const r = resolveItem(w, ctx); if (!r) return;
      if (r.isMat) matFee += r.fee;
      else { totalHours += r.hours; labor += r.fee; }
      rows.push(r);
    });
    // 施工组织建议先算：设备天数要跟着建议工期走（2026-11-22 修：此前固定 1 天，
    // 中空项目按建议干 3 天也只算 1 天吊篮）。
    const crew = calcCrew(totalHours, p.crewTarget || 'auto', p);
    // 设备天数：equipAuto=1 时取建议工期向上取整（至少 1 天）；否则用配置的固定天数。
    const autoEquipDays = !!Number(p.equipAuto) && crew && crew.planDays > 0;
    // 本单设备天数覆盖（ctx.equipDays>0 时优先，测算器「施工条件」可填；0/空=沿用自动或配置）
    const equipOverride = Math.max(0, Number(ctx.equipDays) || 0);
    const equipDays = equipOverride > 0
      ? equipOverride
      : (autoEquipDays ? Math.max(1, Math.ceil(crew.planDays - 1e-9)) : Math.max(1, Number(p.equipDays) || 1));
    let equip = 0;
    if (ctx.height === 'mid') equip = p.equipMid * equipDays;
    else if (ctx.height === 'high') equip = p.equipHigh * equipDays;
    // 运输费按公里：里程由测算器本单输入，单价取单价库 transport（元/公里，默认2）。
    // 市内运输通常往返（去+回），ctx.roundTrip 为真时里程×2。
    const km = Math.max(0, Number(ctx.distanceKm) || 0);
    const kmRate = Math.max(0, Number(ctx.transportRate) || 0);
    const roundTrip = !!ctx.roundTrip;
    const billableKm = roundTrip ? km * 2 : km;
    const transportFee = Math.round(billableKm * kmRate * 100) / 100;
    let construction = labor + equip + transportFee;
    // 最低起步价：只补施工费口径（人工+设备+里程运输/清单里的运输费），材料另计。
    // floor 单列展示，不伪造工时/人工费行。
    const floorTarget = Math.max(0, Number(p.minStart) || 0);
    const floor = floorTarget > 0 && construction < floorTarget
      ? Math.round((floorTarget - construction) * 100) / 100 : 0;
    construction += floor;
    // 辅材费：材料费 × 辅材费率（默认6%，0=关闭）。此前价目表里写了费率但从未参与计算（2026-11-22 修）。
    const auxRatio = Math.max(0, Number(p.auxRatio) || 0);
    const auxFee = Math.round(matFee * auxRatio / 100 * 100) / 100;
    const matTotal = Math.round((matFee + auxFee) * 100) / 100;
    const grand = Math.round((construction + matTotal) * 100) / 100;
    // 人天换算统一用配置的每人每天工时（此前硬编码 8，与 calcCrew 口径打架）
    const days = totalHours / dayHours;
    // 对比工程部报价：默认对比「合计（含材料+辅材）」——工程部通常报整单含料价，
    // 若只对比施工费，材料越贵越显得"虚高"（2026-11-22 修）。
    // ctx.compareBase='construction' 可切回只比施工费。
    const compareBase = (ctx.compareBase === 'construction') ? 'construction' : 'grand';
    const base = compareBase === 'grand' ? grand : construction;
    const q = parseFloat(ctx.quote);
    let compare = null;
    if (!isNaN(q) && q > 0) {
      const diff = Math.round((q - base) * 100) / 100;
      const pct = base > 0 ? diff / base * 100 : 0;
      compare = { quote: q, diff, pct, over: diff > 0, base, baseLabel: compareBase };
    }
    // 与测算器原 calcWork 一致：totalHours 保留原始精度，不在内核层四舍五入
    // （原逻辑只在显示时 toFixed(1)，若在此取整会导致 labor = 工时×单价 与显示工时×单价对不上）
    return {
      rows, totalHours, days, labor, equip, equipDays, transportFee, distanceKm: km, transportRate: kmRate,
      roundTrip, billableKm,
      matFee, auxRatio, auxFee, matTotal, construction, floor, floorTarget, grand,
      total: construction, crew, compare, compareBase,
      params: { height: ctx.height || 'low', wall: ctx.wall || 'flat', quote: ctx.quote || 0,
        rate: { normal: p.rateNormal, high: p.rateHigh }, WP: p }
    };
  }

  // ============ 报价文本（复制明细） ============
  function quoteText(r, info) {
    info = info || {};
    const L = [];
    if (info.company) L.push(info.company);
    if (info.title) L.push(info.title);
    const line = [];
    if (info.customer) line.push('客户：' + info.customer);
    if (info.no) line.push('单号：' + info.no);
    if (line.length) L.push(line.join('  '));
    L.push('日期：' + new Date().toLocaleDateString('zh-CN'));
    L.push('————————————————');
    (r.rows || []).forEach((x) => {
      L.push(x.n + '  ' + (x.q || '') + (x.u || '') + '  =  ' + money(x.fee) + (x.isMat ? '（材料）' : ''));
      if (x.note) L.push('    ' + x.note);
    });
    L.push('————————————————');
    L.push('工时：' + r.totalHours + ' 小时（约 ' + r.days + ' 人天）');
    L.push('人工费：' + money(r.labor) + '   设备费：' + money(r.equip) + (r.equipDays > 1 ? '（' + r.equipDays + '天）' : ''));
    if (r.transportFee > 0) L.push('运输费：' + money(r.transportFee) + '（' + (r.roundTrip ? r.distanceKm + '公里往返 × ' : r.distanceKm + '公里 × ') + money(r.transportRate) + '/公里）');
    if (r.floor > 0) L.push('最低起步价补足：' + money(r.floor) + '（施工费不足 ' + money(r.floorTarget) + '）');
    L.push('施工费小计：' + money(r.construction));
    if (r.matFee > 0) L.push('材料费：' + money(r.matFee));
    if (r.auxFee > 0) L.push('辅材费：' + money(r.auxFee) + '（材料 ' + r.auxRatio + '%）');
    if (r.matTotal > 0 || r.auxFee > 0) L.push('总计：' + money(r.grand));
    if (r.crew) L.push('施工组织建议：' + (r.crew.solo ? '1 人即可' : '建议 ' + r.crew.people + ' 人，约 ' + r.crew.planDays + ' 天'));
    if (r.compare) {
      const baseName = r.compare.baseLabel === 'construction' ? '测算施工费' : '测算合计';
      L.push('工程部报价 ' + money(r.compare.quote) + '：' + (r.compare.over
        ? '高出' + baseName + ' ' + money(r.compare.diff) + '（+' + r.compare.pct.toFixed(0) + '%）'
        : '低于' + baseName + ' ' + money(-r.compare.diff) + '（建议不低于 ' + money(r.compare.base) + '）'));
    }
    return L.join('\n');
  }

